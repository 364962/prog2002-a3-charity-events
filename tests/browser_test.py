"""Browser acceptance checks. Run via api/scripts/browser-check.js against a disposable database."""
import json, os
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

BASE = os.environ.get('BASE_URL', 'http://127.0.0.1:3088')
OUT = Path(os.environ.get('QA_OUTPUT', 'tmp/qa'))
OUT.mkdir(parents=True, exist_ok=True)
results = []

def run(browser_type):
    browser = browser_type.launch(headless=True)
    context = browser.new_context(viewport={'width':1440,'height':1000})
    page = context.new_page()
    js_errors=[]
    page.on('pageerror', lambda error: js_errors.append(str(error)))
    def visit(path):
        page.goto(BASE+path,wait_until='networkidle')
    def passed(name):
        results.append({'browser':browser_type.name,'check':name,'result':'passed'})
    response = context.request.get(BASE+'/api/events')
    assert response.ok, 'The events API must be available for browser checks'
    events = response.json()['data']
    expected_count = len(events)
    expected_current = sum(event['event_status']=='current' for event in events)
    assert expected_count > 0, 'The sample dataset must contain upcoming events'
    visit('/')
    expect(page.locator('.event-card')).to_have_count(expected_count)
    assert page.locator('.event-card').filter(has_text='Winter warmth walk').count()==0
    assert page.locator('.event-card').filter(has_text='Community gala review').count()==0
    expect(page.locator('.status-pill.current')).to_have_count(expected_current)
    expect(page.locator('.category-chip')).to_have_count(7)
    expect(page.locator('.card-title')).to_have_text([event['name'] for event in events])
    passed('Home matches API events and current status, with category shortcuts; past/suspended excluded')
    page.screenshot(path=str(OUT/f'{browser_type.name}-home-top.png'))
    page.get_by_role('link',name='Fun run',exact=True).click()
    page.wait_for_load_state('networkidle')
    expect(page.locator('.event-card')).to_have_count(2)
    expect(page.locator('#category')).to_have_value('1')
    passed('Home category link restores the filter on Search')
    event=page.request.get(BASE+'/api/events/1').json()['data']
    page.locator('#date').fill(event['starts_at'][:10])
    page.locator('#location').fill('Southport')
    page.locator('#category').select_option('1')
    page.get_by_role('button',name='Find events').click()
    expect(page.locator('.event-card')).to_have_count(1)
    expect(page.locator('.card-title')).to_have_text('Steps for a brighter coast')
    assert 'date=' in page.url and 'location=Southport' in page.url and 'category=1' in page.url
    page.screenshot(path=str(OUT/f'{browser_type.name}-search.png'),full_page=True)
    passed('Date + suburb + category returns one matching event and a shareable URL')
    page.get_by_role('button',name='Clear Filters').click()
    expect(page.locator('.event-card')).to_have_count(expected_count)
    for field in ['date','location','category']: expect(page.locator('#'+field)).to_have_value('')
    passed('Clear Filters resets all DOM controls and reloads all events')
    page.go_back(wait_until='networkidle')
    expect(page.locator('.event-card')).to_have_count(1)
    expect(page.locator('#location')).to_have_value('Southport')
    passed('Browser Back restores prior filters and results')
    page.locator('#location').fill('NoSuchSuburb')
    page.get_by_role('button',name='Find events').click()
    expect(page.locator('#empty-state')).to_be_visible()
    expect(page.locator('.event-card')).to_have_count(0)
    page.get_by_role('button',name='Explore all events').click()
    expect(page.locator('.event-card')).to_have_count(expected_count)
    passed('Empty result and its recovery action')
    visit('/search.html?date=2026-02-30')
    expect(page.locator('#events-error')).to_contain_text('valid date')
    passed('Invalid URL date displays API validation feedback in the DOM')
    page.route('**/api/events?*',lambda route:route.fulfill(status=503,json={'error':'Events are temporarily unavailable. Please try again shortly.'}))
    visit('/search.html')
    expect(page.locator('#events-error')).to_be_visible()
    page.unroute('**/api/events?*')
    page.get_by_role('button',name='Try again').click()
    expect(page.locator('.event-card')).to_have_count(expected_count)
    passed('Service error shown and Retry recovers')
    page.locator('.card-title').filter(has_text='Steps for a brighter coast').click()
    page.wait_for_load_state('networkidle')
    expect(page.locator('h1')).to_have_text('Steps for a brighter coast')
    expect(page.locator('#detail-price')).to_have_text('$25')
    expect(page.locator('#detail-percent')).to_have_text('65%')
    page.locator('#ticket-quantity').select_option('3')
    expect(page.locator('#ticket-total')).to_have_text('$75')
    page.get_by_role('button',name='Register',exact=False).click()
    expect(page.locator('#booking-event-title')).to_have_text('Steps for a brighter coast')
    expect(page.locator('#booking-quantity')).to_have_value('3')
    expect(page.locator('#booking-total')).to_have_text('$75')
    page.get_by_role('button',name='Confirm registration').click()
    expect(page.locator('#registration-error')).to_contain_text('highlighted field')
    page.locator('#full-name').fill('Browser Attendee '+browser_type.name)
    page.locator('#email').fill(browser_type.name+'@example.com')
    page.locator('#phone').fill('0400000000')
    page.screenshot(path=str(OUT/f'{browser_type.name}-registration.png'),full_page=True)
    page.get_by_role('button',name='Confirm registration').click()
    expect(page.locator('#booking-success')).to_be_visible()
    expect(page.locator('#confirmation-details')).to_contain_text('3 tickets')
    page.locator('#view-registration').click()
    expect(page.locator('#registrations-table tbody tr').first).to_contain_text('Browser Attendee '+browser_type.name)
    assert '@example.com' not in page.locator('#registrations-table').inner_text()
    expect(page.locator('#weather-status')).to_contain_text('temporarily unavailable')
    passed('Dedicated registration: validation, saved tickets, confirmation, newest-first public list without contacts; weather failure is non-blocking')
    visit('/registration.html?id=1')
    page.locator('#full-name').fill('Duplicate')
    page.locator('#email').fill(browser_type.name.upper()+'@EXAMPLE.COM')
    page.locator('#phone').fill('0400000000')
    page.get_by_role('button',name='Confirm registration').click()
    expect(page.locator('#registration-error')).to_contain_text('already registered')
    passed('Case-insensitive duplicate email registration is rejected in the browser')
    visit('/event.html?id=2')
    expect(page.locator('#detail-price')).to_have_text('Free entry')
    expect(page.locator('#ticket-total')).to_have_text('Free')
    passed('Zero-priced tickets are explicitly free')
    visit('/event.html?id=11')
    expect(page.locator('#detail-status-label')).to_have_text('Past event')
    expect(page.locator('#registration-form')).not_to_be_visible()
    expect(page.locator('#detail-percent')).to_have_text('110%')
    assert page.locator('#detail-progress').get_attribute('value')=='100'
    passed('Past event cannot register; raised amount above goal stays accurate')
    for path in ['/event.html?id=12','/event.html?id=999','/event.html?id=0','/event.html']:
        visit(path);expect(page.locator('#detail-error')).to_be_visible();expect(page.locator('#event-detail')).not_to_be_visible()
    passed('Suspended, missing and invalid event IDs show helpful errors')
    for width in [390,768,1440]:
        page.set_viewport_size({'width':width,'height':900})
        for path,label in [('/','home'),('/search.html','search'),('/event.html?id=1','detail')]:
            visit(path)
            assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), f'Horizontal overflow: {width} {path}'
            assert page.locator('nav[aria-label="Main navigation"]').is_visible()
            assert page.locator('img').evaluate_all('(images)=>images.every(i=>!i.complete || i.naturalWidth>0)'), 'Broken image'
            if width==390: page.screenshot(path=str(OUT/f'{browser_type.name}-{label}-mobile.png'),full_page=True)
    passed('390px, 768px and 1440px: no horizontal overflow or broken images; navigation visible')
    page.set_viewport_size({'width':390,'height':844})
    visit('/event.html?id=1');page.locator('#register-button').click()
    expect(page.locator('#booking-form')).to_be_visible()
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    passed('Mobile registration navigation and form')
    visit('/not-a-page');expect(page.locator('h1')).to_contain_text('wandered off')
    passed('Custom 404 preserves the navigation')
    page.set_viewport_size({'width':1440,'height':1000})
    visit('/admin/')
    expect(page.locator('#staff-events tbody tr')).to_have_count(12)
    expect(page.locator('#stat-suspended')).to_have_text('1')
    expect(page.locator('#stat-past')).to_have_text('1')
    page.locator('#event-filter').select_option('suspended')
    expect(page.locator('#staff-events tbody tr')).to_have_count(1)
    page.locator('#event-filter').select_option('all')
    page.screenshot(path=str(OUT/f'{browser_type.name}-admin.png'),full_page=True)
    page.get_by_role('button',name='Delete Steps for a brighter coast',exact=True).click()
    page.get_by_role('button',name='Keep event',exact=True).click()
    expect(page.locator('#staff-events tbody tr')).to_have_count(12)
    page.get_by_role('button',name='Delete Steps for a brighter coast',exact=True).click()
    page.get_by_role('button',name='Delete event',exact=True).click()
    expect(page.locator('#admin-error')).to_contain_text('registrations and cannot be deleted')
    passed('Staff lists all statuses; filter works; deletion cancel and registration protection work')
    visit('/admin/event.html?id=1')
    expect(page.locator('#staff-registration-table tbody tr').first).to_contain_text(browser_type.name+'@example.com')
    expect(page.locator('#name')).to_have_value('Steps for a brighter coast')
    page.screenshot(path=str(OUT/f'{browser_type.name}-editor.png'),full_page=True)
    passed('Staff editor loads event and complete registration/contact data')
    visit('/admin/event.html')
    page.locator('#save-event').click()
    expect(page.locator('#admin-error')).to_contain_text('highlighted field')
    values={'name':'Browser event '+browser_type.name,'summary':'A new community event.','description':'An event created during browser acceptance testing.','purpose':'Support the community pantry.','venue':'Community Hall','location':'Southport','address':'18 Community Lane','accessibility':'Step-free access.','ticket_price':'12.50','fundraising_goal':'2000','amount_raised':'150','image_alt':'Gold Coast shoreline','latitude':'-27.967','longitude':'153.414'}
    for field,value in values.items(): page.locator('#'+field).fill(value)
    page.locator('#starts_at').fill(event['starts_at'].replace(' ','T')[:16])
    page.locator('#ends_at').fill(event['ends_at'].replace(' ','T')[:16])
    page.locator('#save-event').click()
    expect(page.locator('#admin-notice')).to_contain_text('Event created')
    new_id=page.url.split('id=')[1]
    assert context.request.get(BASE+'/api/events/'+new_id).json()['data']['name']==values['name']
    page.locator('#name').fill(values['name']+' updated')
    page.locator('#publication_status').select_option('suspended')
    page.locator('#save-event').click()
    expect(page.locator('#admin-notice')).to_contain_text('changes have been saved')
    assert context.request.get(BASE+'/api/events/'+new_id).status==404
    visit('/admin/')
    page.get_by_role('button',name='Delete '+values['name']+' updated',exact=True).click()
    page.keyboard.press('Escape')
    expect(page.locator('#delete-dialog')).not_to_be_visible()
    assert context.request.get(BASE+'/api/admin/events/'+new_id).status==200
    page.get_by_role('button',name='Delete '+values['name']+' updated',exact=True).click()
    page.get_by_role('button',name='Delete event',exact=True).click()
    expect(page.locator('#admin-notice')).to_contain_text('Deleted')
    expect(page.locator('#staff-events tbody tr')).to_have_count(12)
    passed('Staff event create, update, suspension visibility and eligible deletion persist via API')
    visit('/admin/categories.html')
    page.get_by_role('button',name='Delete Fun run',exact=True).click()
    page.get_by_role('button',name='Delete category',exact=True).click()
    expect(page.locator('#admin-error')).to_contain_text('in use')
    page.locator('#category-name').fill('Browser category '+browser_type.name)
    page.locator('#category-description').fill('A test category.')
    page.locator('#save-category').click()
    expect(page.locator('#admin-notice')).to_contain_text('created')
    page.get_by_role('button',name='Edit Browser category '+browser_type.name,exact=True).click()
    page.locator('#category-name').fill('Updated category '+browser_type.name)
    page.locator('#save-category').click()
    expect(page.locator('#admin-notice')).to_contain_text('updated')
    page.get_by_role('button',name='Delete Updated category '+browser_type.name,exact=True).click()
    page.keyboard.press('Escape')
    expect(page.locator('#category-delete-dialog')).not_to_be_visible()
    expect(page.get_by_role('button',name='Delete Updated category '+browser_type.name,exact=True)).to_be_visible()
    page.get_by_role('button',name='Delete Updated category '+browser_type.name,exact=True).click()
    page.get_by_role('button',name='Delete category',exact=True).click()
    expect(page.locator('#admin-notice')).to_contain_text('deleted')
    expect(page.locator('#category-table tbody tr')).to_have_count(6)
    passed('Category create, update and delete; in-use category deletion blocked')
    for width in [390,768,1440]:
        page.set_viewport_size({'width':width,'height':900})
        for path,label in [('/registration.html?id=1','booking'),('/admin/','staff'),('/admin/event.html?id=1','editor'),('/admin/categories.html','categories')]:
            visit(path)
            assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), f'Horizontal overflow {width} {path}'
            if width==390: page.screenshot(path=str(OUT/f'{browser_type.name}-{label}-mobile.png'),full_page=True)
    passed('New registration and staff pages fit 390px, 768px and 1440px; tables scroll within containers')
    for path in ['/registration.html?id=11','/registration.html?id=12','/registration.html?id=0','/registration.html']:
        visit(path);expect(page.locator('#registration-error')).to_be_visible();expect(page.locator('#booking-form')).not_to_be_visible()
    passed('Registration rejects past, suspended, invalid and missing events')
    assert js_errors==[],js_errors
    passed('No uncaught JavaScript errors')
    context.close();browser.close()

with sync_playwright() as p:
    run(p.chromium)
    run(p.webkit)
OUT.joinpath('browser-results.json').write_text(json.dumps(results,indent=2))
print(f'{len(results)} browser acceptance checks passed in Chromium and WebKit.')
